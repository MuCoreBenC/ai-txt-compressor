//! 中文停用词表（用于 TextRank 词集计算时排除虚词）

use once_cell::sync::Lazy;
use std::collections::HashSet;

static STOPWORDS: Lazy<HashSet<&'static str>> = Lazy::new(|| {
    const WORDS: &[&str] = &[
        // 助词
        "的", "了", "着", "过", "吧", "呢", "啊", "哦", "呀", "嘛", "嗯", "啦", "喽", "哎",
        "唉", "嗨", "喂", "地", "得",
        // 代词
        "我", "你", "他", "她", "它", "我们", "你们", "他们", "她们", "它们", "自己", "人",
        "大家", "谁", "什么", "怎么", "为什么", "哪里", "哪个", "哪些", "多少",
        // 指示代词
        "这", "那", "这个", "那个", "这些", "那些", "这里", "那里", "这样", "那样", "此",
        "彼", "其",
        // 介词/连词
        "在", "和", "与", "同", "跟", "或", "及", "并", "且", "但", "因", "故", "若", "虽",
        "经", "向", "为", "对", "由", "从", "把", "被", "让", "使", "给", "于", "以",
        // 副词
        "很", "较", "已", "现", "后", "前", "又", "也", "还", "都", "就", "只", "才", "再",
        "便", "即", "一", "一个", "一些", "上", "下", "里", "外", "内", "间",
        // 动词/助动词
        "是", "有", "没", "没有", "能", "可", "会", "要", "去", "来", "到", "做", "看", "说",
        "想", "认", "始", "终",
        // 量词
        "个", "位", "名", "项", "件", "次", "回", "场", "段", "篇", "本", "册",
        // 时间/方位（高频虚词）
        "的", "了", "在", "是", "我", "有", "和", "就", "不", "人", "都", "一", "上", "也",
        // 双字连接词
        "因为", "所以", "如果", "虽然", "尽管", "即使", "除非", "只要", "只有", "为了",
        "由于", "于是", "因此", "因而", "但是", "可是", "然而", "只是", "不过", "而且",
        "并且", "或者", "还是", "以及", "可以", "可能", "应该", "必须", "也许", "大概",
        "肯定", "已经", "正在", "将要", "曾经", "马上", "立刻", "现在", "目前", "之前",
        "之后", "通过", "根据", "按照", "依据", "关于", "对于", "至于", "针对",
    ];
    let mut s = HashSet::new();
    for w in WORDS {
        s.insert(*w);
    }
    s
});

pub fn is_stopword(word: &str) -> bool {
    STOPWORDS.contains(word)
}
